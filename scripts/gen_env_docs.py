"""Generate `.env.example` and `infra/ENV.md` from `Settings` (run via `make env-docs`).

Nothing else edits those two files by hand: `make check` regenerates them and fails on a diff.
"""

import sys
from pathlib import Path

from pydantic import BaseModel
from pydantic.fields import FieldInfo
from pydantic_core import PydanticUndefined

from saveclock.config import COMPOSE_ONLY, MigrateSettings, Settings

ROOT = Path(__file__).resolve().parent.parent


def _type(f: FieldInfo) -> str:
    return str(f.annotation).replace("typing.", "").replace("<class '", "").replace("'>", "")


def _default(f: FieldInfo) -> str:
    if f.is_required():
        return ""
    d = f.default
    if d is PydanticUndefined or d is None:
        return ""
    return ",".join(d) if isinstance(d, list) else str(d)


def _rows(model: type[BaseModel]) -> list[tuple[str, FieldInfo]]:
    return [(name.upper(), f) for name, f in model.model_fields.items()]


def env_example() -> str:
    out = [
        "# GENERATED by scripts/gen_env_docs.py from saveclock.config. Do not edit by hand.",
        "# `make env` copies this to .env and fills every placeholder secret with a random value.",
        "# Lines starting with # show the default; Settings owns every name (infra/ENV.md).",
        "",
        "# compose-only secrets (C10)",
    ]
    for c in COMPOSE_ONLY:
        out += [f"# {c.doc}", f"{c.name}=CHANGE_ME"]
    for model in (Settings, MigrateSettings):
        out.append("")
        out.append(f"# {model.__name__}")
        for name, f in _rows(model):
            extra = f.json_schema_extra if isinstance(f.json_schema_extra, dict) else {}
            if "example" in extra:
                out.append(f"{name}={extra['example']}")
            else:
                out.append(f"# {name}={_default(f)}")
    return "\n".join(out) + "\n"


def env_md() -> str:
    out = [
        "<!-- GENERATED by scripts/gen_env_docs.py from saveclock.config. Do not edit by hand. -->",
        "# Environment variables",
        "",
        "| Name | Type | Default | Required | Secret | Service | Owner doc |",
        "|---|---|---|---|---|---|---|",
    ]
    for model in (Settings, MigrateSettings):
        for name, f in _rows(model):
            extra = f.json_schema_extra if isinstance(f.json_schema_extra, dict) else {}
            out.append(
                f"| `{name}` | `{_type(f)}` | `{_default(f)}` | "
                f"{'yes' if f.is_required() else 'no'} | {'yes' if extra.get('secret') else 'no'} | "
                f"{extra.get('svc', '')} | {extra.get('doc', '')} |"
            )
    for c in COMPOSE_ONLY:
        out.append(f"| `{c.name}` | `str` | `` | yes | yes | compose | {c.doc} |")
    return "\n".join(out) + "\n"


def main() -> int:
    (ROOT / ".env.example").write_text(env_example())
    (ROOT / "infra" / "ENV.md").write_text(env_md())
    return 0


if __name__ == "__main__":
    sys.exit(main())
